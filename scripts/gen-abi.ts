import { readFileSync, writeFileSync } from "node:fs";

const PAYROLL_JSON = "contracts/out/Payroll.sol/Payroll.json";
const FACTORY_JSON = "contracts/out/PaydayFactory.sol/PaydayFactory.json";
const OUT = "src/proof/abi.ts";

function loadAbi(path: string): unknown[] {
  const raw = JSON.parse(readFileSync(path, "utf8")) as { abi: unknown[] };
  return raw.abi;
}

const payrollAbi = loadAbi(PAYROLL_JSON);
const factoryAbi = loadAbi(FACTORY_JSON);

const lines: string[] = [
  `// Generated by scripts/gen-abi.ts -- do not edit by hand.`,
  `import { erc20Abi } from "viem";`,
  `export { erc20Abi };`,
  ``,
  `export const payrollAbi = ${JSON.stringify(payrollAbi, null, 2)} as const;`,
  ``,
  `export const factoryAbi = ${JSON.stringify(factoryAbi, null, 2)} as const;`,
  ``,
];

writeFileSync(OUT, lines.join("\n"));
process.stdout.write(`wrote ${OUT}\n`);
