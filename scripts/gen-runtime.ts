/**
 * Reads the deployed-bytecode objects from Foundry artifacts and writes
 * src/generated/runtime.ts so the browser proof page can compare them
 * against what is live on Arc mainnet without a separate Foundry invocation.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

function readArtifact(name: string): string {
  const path = `contracts/out/${name}.sol/${name}.json`;
  if (!existsSync(path)) {
    process.stderr.write(`error: artifact not found at ${path}. Run bun run contracts:build first.\n`);
    process.exit(1);
  }
  const raw = JSON.parse(readFileSync(path, 'utf8')) as {
    deployedBytecode?: { object?: string };
  };
  const hex = raw?.deployedBytecode?.object ?? '';
  if (!hex || hex === '0x') {
    process.stderr.write(`error: empty deployedBytecode in ${path}\n`);
    process.exit(1);
  }
  return hex;
}

const factory = readArtifact('PaydayFactory');
const payroll = readArtifact('Payroll');

const out = `// Generated by scripts/gen-runtime.ts from Foundry artifacts. Do not edit.
export const LOCAL_RUNTIME = {
  factory: '${factory}' as const,
  payroll: '${payroll}' as const,
} as const;
`;

writeFileSync('src/generated/runtime.ts', out, 'utf8');
process.stdout.write('src/generated/runtime.ts written.\n');
